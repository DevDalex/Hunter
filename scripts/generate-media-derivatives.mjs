import { execFile } from 'node:child_process';
import { access, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { promisify } from 'node:util';
import { blackWhaleRoomMedia } from '../src/data/blackWhaleMedia.generated.js';
import { priorityPortraits } from '../src/data/priorityMedia.generated.js';
import { readWebpDimensions } from './lib/mediaPipeline.mjs';

const execFileAsync = promisify(execFile);
const root = process.cwd();
const outputRoot = path.join(root, 'public/media/derivatives');
const manifestPath = path.join(root, 'src/data/mediaDerivatives.generated.js');
const verifyOnly = process.argv.includes('--verify-only');
const targetWidths = Object.freeze([320, 640, 960]);
const records = [...priorityPortraits, ...blackWhaleRoomMedia].filter((record) => record.storage === 'local' && record.src?.startsWith('/media/'));

const commandCandidates = [
  { command: 'magick', prefix: [] },
  { command: 'convert', prefix: [] },
];

const findConverter = async () => {
  for (const candidate of commandCandidates) {
    try {
      await execFileAsync(candidate.command, ['-version'], { timeout: 5000 });
      return candidate;
    } catch {
      // Try the next compatible ImageMagick entry point.
    }
  }
  return null;
};

const derivativePath = (record, width) => {
  const relative = record.src.replace(/^\/media\//, '');
  const extension = path.extname(relative);
  const stem = relative.slice(0, -extension.length);
  return `/media/derivatives/${stem}-${width}.webp`;
};

const sizesFor = (record) => record.src.startsWith('/media/portraits/')
  ? '(max-width: 480px) 70vw, 360px'
  : '(max-width: 900px) 100vw, 1100px';

const renderManifest = (entries, available) => {
  const lines = entries.map((entry) => `  Object.freeze(${JSON.stringify(entry)}),`);
  return `// Generated by scripts/generate-media-derivatives.mjs. Do not edit individual entries by hand.\nexport const MEDIA_DERIVATIVES_AVAILABLE = ${available ? 'true' : 'false'};\nexport const mediaDerivatives = Object.freeze([\n${lines.join('\n')}\n]);\nexport const mediaDerivativeBySrc = new Map(mediaDerivatives.map((record) => [record.src, record]));\n`;
};

const verifyManifest = async () => {
  const url = `${pathToFileURL(manifestPath).href}?verify=${Date.now()}`;
  const manifest = await import(url);
  if (!manifest.MEDIA_DERIVATIVES_AVAILABLE) {
    if (manifest.mediaDerivatives.length !== 0) throw new Error('Unavailable derivative manifest must be empty.');
    console.log('Responsive media derivatives unavailable in this environment; verified original-only fallback manifest.');
    return;
  }
  if (!manifest.mediaDerivatives.length) throw new Error('Derivative manifest claims availability but contains no records.');
  const known = new Set(records.map((record) => record.src));
  for (const entry of manifest.mediaDerivatives) {
    if (!known.has(entry.src)) throw new Error(`Unknown original in derivative manifest: ${entry.src}`);
    if (!Array.isArray(entry.candidates) || !entry.candidates.length) throw new Error(`${entry.src}: no derivative candidates`);
    if (!entry.srcSet.includes(entry.src)) throw new Error(`${entry.src}: original is not retained in srcSet`);
    for (const candidate of entry.candidates) {
      if (!candidate.src.startsWith('/media/derivatives/')) throw new Error(`${entry.src}: derivative escaped local derivative namespace`);
      const file = path.join(root, 'public', candidate.src.slice(1));
      await access(file);
      const dimensions = await readWebpDimensions(file);
      if (dimensions.width !== candidate.width || dimensions.height !== candidate.height) throw new Error(`${candidate.src}: manifest dimensions do not match generated file`);
    }
  }
  console.log(`Responsive media derivatives verified: ${manifest.mediaDerivatives.length} originals expose ${manifest.mediaDerivatives.reduce((sum, record) => sum + record.candidates.length, 0)} generated WebP candidates.`);
};

if (verifyOnly) {
  await readFile(manifestPath, 'utf8');
  await verifyManifest();
  process.exit(0);
}

const converter = await findConverter();
if (!converter) {
  await rm(outputRoot, { recursive: true, force: true });
  await writeFile(manifestPath, renderManifest([], false));
  console.warn('ImageMagick was not found; responsive derivative generation was skipped and originals remain authoritative.');
  process.exit(0);
}

await rm(outputRoot, { recursive: true, force: true });
await mkdir(outputRoot, { recursive: true });
const entries = [];

for (const record of records) {
  const originalFile = path.join(root, 'public', record.src.slice(1));
  await access(originalFile);
  const candidates = [];
  for (const width of targetWidths.filter((value) => value < record.width)) {
    const publicPath = derivativePath(record, width);
    const outputFile = path.join(root, 'public', publicPath.slice(1));
    await mkdir(path.dirname(outputFile), { recursive: true });
    await execFileAsync(converter.command, [
      ...converter.prefix,
      originalFile,
      '-auto-orient',
      '-resize', `${width}x>`,
      '-strip',
      '-quality', '80',
      outputFile,
    ], { timeout: 30000 });
    const dimensions = await readWebpDimensions(outputFile);
    candidates.push(Object.freeze({ src: publicPath, width: dimensions.width, height: dimensions.height }));
  }
  if (!candidates.length) continue;
  const srcSet = [...candidates.map((candidate) => `${candidate.src} ${candidate.width}w`), `${record.src} ${record.width}w`].join(', ');
  entries.push(Object.freeze({
    src: record.src,
    width: record.width,
    height: record.height,
    sizes: sizesFor(record),
    candidates,
    srcSet,
  }));
}

await writeFile(manifestPath, renderManifest(entries, entries.length > 0));
await verifyManifest();
console.log(`Responsive media generation complete with ${converter.command}: ${entries.length}/${records.length} verified originals received smaller derivatives.`);
