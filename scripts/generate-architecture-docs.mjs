import { readFile, writeFile } from 'node:fs/promises';
import { canonicalSuccessionRoutes, legacyRouteRedirects } from '../src/data/routeRegistry.js';
import { archiveCoverageList, domainCoverage } from '../src/data/archiveCoverage.js';
import { performanceBudgets } from '../src/data/performanceBudgets.js';

const outputPath = 'docs/GENERATED-ARCHITECTURE.md';
const rows = canonicalSuccessionRoutes.map((route) => `| ${route.id} | /${route.path || ''} | ${route.release ? 'yes' : 'no'} | ${route.searchable ? 'yes' : 'no'} |`).join('\n');
const coverageRows = Object.entries(domainCoverage).map(([id, entry]) => `| ${id} | ${entry.label} | ${entry.chapter} | ${entry.status} |`).join('\n');
const boundaryRows = archiveCoverageList.map((entry) => `| ${entry.label} | ${entry.chapter} | ${entry.description} |`).join('\n');
const redirectRows = Object.entries(legacyRouteRedirects).map(([alias, target]) => `| /${alias} | /${target} |`).join('\n');
const budgetRows = Object.entries(performanceBudgets).map(([key, value]) => `| ${key} | ${value} bytes |`).join('\n');

const generated = `# Generated Architecture Inventory\n\n> Generated by \`npm run docs:generate\`. Do not edit by hand.\n\n## Chapter boundaries\n\n| Boundary | Chapter | Meaning |\n|---|---:|---|\n${boundaryRows}\n\n## Canonical routes\n\n| ID | Path | Released | Searchable |\n|---|---|---|---|\n${rows}\n\n## Legacy redirects\n\n| Legacy path | Canonical target |\n|---|---|\n${redirectRows}\n\n## Domain coverage\n\n| Domain | Label | Indexed through | Status |\n|---|---|---:|---|\n${coverageRows}\n\n## Performance budgets\n\n| Budget | Limit |\n|---|---:|\n${budgetRows}\n`;

if (process.argv.includes('--check')) {
  const current = await readFile(outputPath, 'utf8').catch(() => '');
  if (current !== generated) {
    console.error(`${outputPath} is stale. Run npm run docs:generate.`);
    process.exit(1);
  }
  console.log('Generated architecture documentation is current.');
} else {
  await writeFile(outputPath, generated);
  console.log(`Wrote ${outputPath}.`);
}
