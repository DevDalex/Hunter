import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  successionArchiveHubs,
  successionArchiveRoutes,
} from '../src/data/succession/archiveRoutes.js';
import {
  SUCCESSION_COMPREHENSION_DESIGN_SYSTEM_VERSION,
  successionInformationHierarchy,
  successionPresentationRules,
  successionSemanticStates,
} from '../src/data/succession/comprehensionDesignSystem.js';
import {
  SUCCESSION_ARCHIVE_BOOKMARK_FOLDER_LIMIT,
  SUCCESSION_ARCHIVE_BOOKMARK_LIMIT,
  SUCCESSION_ARCHIVE_BOOKMARK_TAG_LIMIT,
  SUCCESSION_ARCHIVE_COMPARE_LIMIT,
  SUCCESSION_ARCHIVE_RECENT_LIMIT,
  SUCCESSION_ARCHIVE_SEARCH_LIMIT,
  SUCCESSION_ARCHIVE_WATCHLIST_CITATION_LIMIT,
  SUCCESSION_ARCHIVE_WATCHLIST_LIMIT,
  SUCCESSION_ARCHIVE_WATCHLIST_NOTE_LIMIT,
  SUCCESSION_ARCHIVE_WATCHLIST_STATUSES,
  SUCCESSION_ARCHIVE_WATCHLIST_TAG_LIMIT,
} from '../src/data/succession/archiveMemory.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const target = path.join(root, 'docs/generated/SUCCESSION-ARCHITECTURE.md');
const checkOnly = process.argv.includes('--check');

const cleanCell = (value) => String(value ?? '').replaceAll('|', '\\|').replaceAll('\n', ' ');
const routePath = (route) => route.path ? `/#/succession/${route.path}` : '/#/succession/archive';

export function renderSuccessionArchitectureDocs() {
  const lines = [
    '<!-- Generated by scripts/generate-succession-docs.mjs. Do not edit by hand. -->',
    '',
    '# Succession Architecture & Comprehension Contract',
    '',
    `Generated from canonical source modules. Design-system contract: **${SUCCESSION_COMPREHENSION_DESIGN_SYSTEM_VERSION}**.`,
    '',
    '## Canonical route registry',
    '',
    `Maintained routes: **${successionArchiveRoutes.length}**. Canonical route ownership stays in \`src/data/succession/archiveRoutes.js\`.`,
    '',
    '| ID | URL | Group | Status | Title |',
    '| --- | --- | --- | --- | --- |',
    ...successionArchiveRoutes.map((route) => `| ${cleanCell(route.id)} | \`${cleanCell(routePath(route))}\` | ${cleanCell(route.group)} | ${cleanCell(route.status)} | ${cleanCell(route.title)} |`),
    '',
    '## Hub registry',
    '',
    `Maintained hubs: **${successionArchiveHubs.length}**.`,
    '',
    '| Hub | Target | Tabs |',
    '| --- | --- | --- |',
    ...successionArchiveHubs.map((hub) => `| ${cleanCell(hub.label)} | \`${cleanCell(hub.target)}\` | ${cleanCell(hub.tabs.map((tab) => `${tab.label} → ${tab.target}`).join(' · ') || 'Direct workspace')} |`),
    '',
    '## Information hierarchy',
    '',
    ...successionInformationHierarchy.map((level, index) => `${index + 1}. **${level.label}** — ${level.purpose}`),
    '',
    '## Semantic state vocabulary',
    '',
    '| State | Label | Role | CSS contract |',
    '| --- | --- | --- | --- |',
    ...successionSemanticStates.map((state) => `| \`${cleanCell(state.id)}\` | ${cleanCell(state.label)} | ${cleanCell(state.role)} | \`${cleanCell(state.cssClass)}\` |`),
    '',
    '## Presentation invariants',
    '',
    ...successionPresentationRules.map((rule) => `- ${rule}`),
    '',
    '## Local research-memory schema limits',
    '',
    'Research Memory is browser-local personal material. These limits are presentation/storage safety boundaries and do not change canonical archive data.',
    '',
    '| Field | Limit / values |',
    '| --- | --- |',
    `| Recent archive contexts | ${SUCCESSION_ARCHIVE_RECENT_LIMIT} |`,
    `| Archive bookmarks | ${SUCCESSION_ARCHIVE_BOOKMARK_LIMIT} |`,
    `| Bookmark tags | ${SUCCESSION_ARCHIVE_BOOKMARK_TAG_LIMIT} per bookmark |`,
    `| Bookmark folder name | ${SUCCESSION_ARCHIVE_BOOKMARK_FOLDER_LIMIT} characters |`,
    `| Compare tray | ${SUCCESSION_ARCHIVE_COMPARE_LIMIT} records |`,
    `| Saved searches | ${SUCCESSION_ARCHIVE_SEARCH_LIMIT} |`,
    `| Research collections | ${SUCCESSION_ARCHIVE_WATCHLIST_LIMIT} |`,
    `| Investigation note | ${SUCCESSION_ARCHIVE_WATCHLIST_NOTE_LIMIT} characters |`,
    `| Investigation tags | ${SUCCESSION_ARCHIVE_WATCHLIST_TAG_LIMIT} |`,
    `| Selected citations | ${SUCCESSION_ARCHIVE_WATCHLIST_CITATION_LIMIT} |`,
    `| Investigation status | ${SUCCESSION_ARCHIVE_WATCHLIST_STATUSES.map((status) => `\`${status}\``).join(' · ')} |`,
    '',
    '## Source-of-truth modules',
    '',
    '- `src/data/succession/archiveRoutes.js` — canonical route and hub ownership.',
    '- `src/data/succession/successionData.js` — released canonical graph selectors.',
    '- `src/data/succession/comprehensionDesignSystem.js` — semantic states, hierarchy, presentation rules.',
    '- `src/data/succession/archiveMemory.js` — local research-memory schema and bounds.',
    '- `src/components/succession-reader/readerState.js` — authoritative manga Reader page/progress persistence.',
    '',
    '## Regeneration',
    '',
    '- `npm run docs:generate` rewrites this file.',
    '- `npm run docs:check` regenerates in memory and fails when the committed file is stale.',
    '',
  ];
  return `${lines.join('\n')}\n`;
}

const rendered = renderSuccessionArchitectureDocs();
if (checkOnly) {
  let committed = '';
  try { committed = await readFile(target, 'utf8'); }
  catch { throw new Error(`Generated Succession docs are missing: ${path.relative(root, target)}. Run npm run docs:generate.`); }
  if (committed !== rendered) throw new Error(`Generated Succession docs are stale: ${path.relative(root, target)}. Run npm run docs:generate and commit the result.`);
  console.log(`Succession generated docs are current: ${path.relative(root, target)}.`);
} else {
  await mkdir(path.dirname(target), { recursive: true });
  await writeFile(target, rendered, 'utf8');
  console.log(`Generated ${path.relative(root, target)}.`);
}
