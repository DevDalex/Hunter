import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = path.join(root, 'src/data/siteStats.source.json');
const outputPath = path.join(root, 'src/data/siteStats.generated.js');

const source = JSON.parse(await readFile(sourcePath, 'utf8'));
for (const [key, value] of Object.entries(source)) {
  if (!Number.isInteger(value) || value < 0) {
    throw new Error(`Site statistic ${key} must be a non-negative integer.`);
  }
}

const output = `// Generated by scripts/generate-site-stats.mjs. Do not edit directly.\nexport const SITE_STATS = Object.freeze(${JSON.stringify(source, null, 2)});\n`;
await writeFile(outputPath, output, 'utf8');
console.log(`Generated ${path.relative(root, outputPath)} with ${Object.keys(source).length} statistics.`);
