#!/usr/bin/env node

import { createHash } from 'node:crypto';
import { readdir, readFile, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { authorizedSuccessionChapterMedia } from '../src/data/successionChapterMedia.generated.js';
import { detectImage } from '../server/chapter-admin.js';

const ROOT = process.cwd();
const MEDIA_ROOT = path.join(ROOT, 'public', 'media', 'succession-contest', 'chapters');
const MANIFEST_PATH = path.join(ROOT, 'src', 'data', 'successionChapterMedia.generated.js');
const DRY_RUN = process.argv.includes('--dry-run');
const SUPPORTED = new Set(['.jpg', '.jpeg', '.png', '.webp']);
const naturalSort = new Intl.Collator('en', { numeric: true, sensitivity: 'base' });
const nextManifest = {};

const mediaStats = await stat(MEDIA_ROOT).catch(() => null);
if (!mediaStats?.isDirectory()) throw new Error(`Chapter media root does not exist: ${MEDIA_ROOT}`);

const chapterDirectories = (await readdir(MEDIA_ROOT, { withFileTypes: true }))
  .filter((entry) => entry.isDirectory() && /^\d+$/.test(entry.name))
  .map((entry) => Number(entry.name))
  .filter((chapter) => chapter >= 339 && chapter <= 414)
  .sort((left, right) => left - right);

for (const chapter of chapterDirectories) {
  const directory = path.join(MEDIA_ROOT, String(chapter));
  const files = (await readdir(directory, { withFileTypes: true }))
    .filter((entry) => entry.isFile() && SUPPORTED.has(path.extname(entry.name).toLowerCase()))
    .map((entry) => entry.name)
    .sort((left, right) => naturalSort.compare(left, right));
  if (!files.length) continue;

  const previous = authorizedSuccessionChapterMedia[chapter] || [];
  const importedAt = previous.find((page) => page.importedAt)?.importedAt || new Date().toISOString();
  const pages = [];
  for (const [index, filename] of files.entries()) {
    const page = index + 1;
    const padded = String(page).padStart(3, '0');
    if (!filename.startsWith(padded)) throw new Error(`Chapter ${chapter} file ${filename} is not sequentially named for p.${page}.`);
    const bytes = new Uint8Array(await readFile(path.join(directory, filename)));
    const image = detectImage(bytes, '', filename);
    const extension = image.extension.slice(1);
    const src = `/media/succession-contest/chapters/${chapter}/${filename}`;
    const old = previous.find((record) => record.page === page) || {};
    pages.push({
      id: `chapter-${chapter}-p${padded}`,
      chapter,
      page,
      label: `p.${page}`,
      filename,
      src,
      localPath: src,
      sourceUrl: old.sourceUrl || null,
      width: image.width,
      height: image.height,
      format: extension,
      byteSize: bytes.byteLength,
      checksum: `sha256-${createHash('sha256').update(bytes).digest('hex')}`,
      status: old.status || 'published',
      importedAt: old.importedAt || importedAt,
    });
  }
  nextManifest[chapter] = pages;
  console.log(`Chapter ${chapter}: rebuilt ${pages.length} page record${pages.length === 1 ? '' : 's'}.`);
}

const content = `// Generated by the Succession chapter import tools.\n// Do not edit page records manually; re-run an importer instead.\nexport const authorizedSuccessionChapterMedia = Object.freeze(${JSON.stringify(nextManifest, null, 2)});\n`;
if (DRY_RUN) {
  console.log(`Dry run complete: ${Object.keys(nextManifest).length} stored chapter folders would be registered.`);
} else {
  await writeFile(MANIFEST_PATH, content, 'utf8');
  console.log(`Rebuilt ${path.relative(ROOT, MANIFEST_PATH)} from ${Object.keys(nextManifest).length} stored chapter folders.`);
}
