const ARCHIVE_DATE = '2026-07-24';

const slugify = (value = '') => String(value)
  .normalize('NFKD')
  .replace(/[\u0300-\u036f]/g, '')
  .toLowerCase()
  .replace(/&/g, ' and ')
  .replace(/[^a-z0-9]+/g, '-')
  .replace(/^-+|-+$/g, '');

const characterId = (name) => `character:${slugify(name)}`;
const guardianBeastId = (host) => `guardian-beast:${slugify(host)}`;
const chapterSourceId = (number) => `source:chapter-${number}`;
const unique = (values) => [...new Set(values.filter(Boolean))];

const ability = ({
  slug,
  name,
  aliases = [],
  summary,
  owners = [],
  ownerIds = [],
  nenTypes = ['unknown'],
  certainty = 'confirmed',
  canonLevel = 'canon',
  category,
  activation,
  conditions = [],
  limitations = [],
  costs = [],
  targets = [],
  range = 'unknown',
  duration = 'unknown',
  status = 'active',
  knownUses = [],
  sourceChapters,
  researchStatus = 'documented',
}) => Object.freeze({
  id: `ability:${slug}`,
  entityType: 'ability',
  slug,
  name,
  aliases: Object.freeze(aliases),
  summary,
  sourceIds: Object.freeze(unique(sourceChapters.map(chapterSourceId))),
  publicationStatus: 'published',
  canonLevel,
  createdAt: ARCHIVE_DATE,
  updatedAt: ARCHIVE_DATE,
  ownerIds: Object.freeze(unique([
    ...owners.map(characterId),
    ...ownerIds,
  ])),
  classification: Object.freeze({
    nenTypes: Object.freeze(nenTypes),
    certainty,
  }),
  category,
  activation,
  conditions: Object.freeze(conditions),
  limitations: Object.freeze(limitations),
  costs: Object.freeze(costs),
  targets: Object.freeze(targets),
  range,
  duration,
  status,
  knownUses: Object.freeze(knownUses),
  firstChapter: Math.min(...sourceChapters),
  latestChapter: Math.max(...sourceChapters),
  sourceChapterNumbers: Object.freeze([...sourceChapters]),
  researchStatus,
});

