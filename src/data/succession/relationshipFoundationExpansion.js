const chapterSourceId = (number) => `source:chapter-${number}`;
const eventId = (slug) => `event:${slug}`;
const characterId = (slug) => `character:${slug}`;
const organizationId = (slug) => `organization:${slug}`;
const unique = (values) => [...new Set(values.filter(Boolean))];

const relationship = ({
  slug,
  name,
  aliases = [],
  summary,
  sourceEntityId,
  targetEntityId,
  relationshipType,
  subtype,
  direction = 'directed',
  sentiment = 'neutral',
  status = 'active',
  start,
  end = null,
  basis,
  operationalState,
  strength = 'material',
  certainty = 'confirmed',
  relatedEvents = [],
  evidenceNotes = [],
  canonLevel = 'canon',
  sources,
}) => Object.freeze({
  id: `relationship:${slug}`,
  entityType: 'relationship',
  slug,
  name,
  aliases: Object.freeze(aliases),
  summary,
  sourceIds: Object.freeze(unique((sources || [start]).map(chapterSourceId))),
  publicationStatus: 'published',
  canonLevel,
  createdAt: ARCHIVE_DATE,
  updatedAt: ARCHIVE_DATE,
  sourceEntityId,
  targetEntityId,
  relationshipType,
  subtype,
  direction,
  sentiment,
  status,
  chapterRange: Object.freeze({ start, end }),
  basis,
  operationalState,
  strength,
  certainty,
  relatedEventIds: Object.freeze(relatedEvents.map(eventId)),
  evidenceNotes: Object.freeze(evidenceNotes),
});

