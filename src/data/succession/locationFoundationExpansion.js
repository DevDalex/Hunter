const ARCHIVE_DATE = '2026-07-24';

const slugify = (value = '') => String(value)
  .normalize('NFKD')
  .replace(/[\u0300-\u036f]/g, '')
  .toLowerCase()
  .replace(/&/g, ' and ')
  .replace(/[^a-z0-9]+/g, '-')
  .replace(/^-+|-+$/g, '');

const characterId = (name) => `character:${slugify(name)}`;
const chapterSourceId = (number) => `source:chapter-${number}`;
const unique = (values) => [...new Set(values.filter(Boolean))];

const shipId = 'location:black-whale';
const tierId = (number) => `${shipId}:tier-${number}`;
const roomId = (number) => `${tierId(1)}:room-${1000 + number}`;
const justiceId = `${tierId(1)}:justice-bureau`;

const location = ({
  id,
  slug,
  name,
  aliases = [],
  summary,
  locationType,
  parentId = null,
  ancestorIds = [],
  deck = null,
  accessLevel = 'restricted',
  zoneRole = 'operational-area',
  canonLevel = 'canon',
  certainty = 'confirmed',
  sourceChapters,
}) => Object.freeze({
  id,
  entityType: 'location',
  slug,
  name,
  aliases: Object.freeze(aliases),
  summary,
  sourceIds: Object.freeze(unique(sourceChapters.map(chapterSourceId))),
  publicationStatus: 'published',
  canonLevel,
  createdAt: ARCHIVE_DATE,
  updatedAt: ARCHIVE_DATE,
  locationType,
  parentId,
  ancestorIds: Object.freeze(ancestorIds),
  deck,
  accessLevel,
  zoneRole,
  certainty,
});

const history = ({
  slug,
  name,
  summary,
  character,
  locationId,
  start,
  end = null,
  state,
  certainty = 'confirmed',
  canonLevel = 'canon',
  sourceChapters,
}) => Object.freeze({
  id: `location-history:${slug}`,
  entityType: 'location-history',
  slug: null,
  name,
  aliases: Object.freeze([]),
  summary,
  sourceIds: Object.freeze(unique(sourceChapters.map(chapterSourceId))),
  publicationStatus: 'published',
  canonLevel,
  createdAt: ARCHIVE_DATE,
  updatedAt: ARCHIVE_DATE,
  characterId: characterId(character),
  locationId,
  chapterRange: Object.freeze({ start, end }),
  state,
  certainty,
});

