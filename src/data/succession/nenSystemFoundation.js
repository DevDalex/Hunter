export const abilitySystemLinks = Object.freeze(Object.fromEntries(
  Object.values(nenSystemProfiles).flatMap((profile) => profile.abilityIds.map((abilityId) => [abilityId, profile.id]))
    .reduce((map, [abilityId, systemId]) => {
      const current = map.get(abilityId) || [];
      current.push(systemId);
      map.set(abilityId, current);
      return map;
    }, new Map()),
));
