const chapterSourceId = (number) => `source:chapter-${number}`;
const freeze = (values) => Object.freeze(values);

const system = ({
  id,
  name,
  summary,
  category,
  start,
  end = null,
  rules = [],
  costs = [],
  risks = [],
  openQuestions = [],
  abilityIds = [],
  guardianBeastIds = [],
  characterIds = [],
  organizationIds = [],
  locationIds = [],
  sources = [],
  certainty = 'confirmed',
}) => Object.freeze({
  id,
  name,
  summary,
  category,
  chapterRange: Object.freeze({ start, end }),
  rules: freeze(rules),
  costs: freeze(costs),
  risks: freeze(risks),
  openQuestions: freeze(openQuestions),
  abilityIds: freeze(abilityIds),
  guardianBeastIds: freeze(guardianBeastIds),
  characterIds: freeze(characterIds),
  organizationIds: freeze(organizationIds),
  locationIds: freeze(locationIds),
  sourceIds: freeze(sources.map(chapterSourceId)),
  certainty,
});

const beastState = ({
  beastId,
  start,
  end = null,
  knowledge,
  operationalState,
  hostState = 'host active',
  visibility = 'visible to eligible Nen users other than the host',
  knownAbilityIds = [],
  suspectedAbilityIds = [],
  unresolved = [],
  sources = [],
  certainty = 'confirmed',
}) => Object.freeze({
  id: `guardian-beast-state:${beastId.replace('guardian-beast:', '')}:${start}`,
  beastId,
  chapterRange: Object.freeze({ start, end }),
  knowledge,
  operationalState,
  hostState,
  visibility,
  knownAbilityIds: freeze(knownAbilityIds),
  suspectedAbilityIds: freeze(suspectedAbilityIds),
  unresolved: freeze(unresolved),
  sourceIds: freeze(sources.map(chapterSourceId)),
  certainty,
});

