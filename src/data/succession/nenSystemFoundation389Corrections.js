const freeze = (value) => Object.freeze(value);
const chapterSourceId = (number) => `source:chapter-${number}`;

const system = ({ id, name, summary, category, start, end = null, rules = [], costs = [], risks = [], openQuestions = [], abilityIds = [], guardianBeastIds = [], characterIds = [], organizationIds = [], locationIds = [], sources = [], certainty = 'confirmed' }) => freeze({
  id,
  name,
  summary,
  category,
  chapterRange: freeze({ start, end }),
  rules: freeze(rules),
  costs: freeze(costs),
  risks: freeze(risks),
  openQuestions: freeze(openQuestions),
  abilityIds: freeze(abilityIds),
  guardianBeastIds: freeze(guardianBeastIds),
  characterIds: freeze(characterIds),
  organizationIds: freeze(organizationIds),
  locationIds: freeze(locationIds),
  sourceIds: freeze(sources.map(chapterSourceId)),
  certainty,
});

const beastState = ({ beastId, start, end = null, knowledge, operationalState, hostState = 'host active', visibility = 'visible to eligible Nen users other than the host', knownAbilityIds = [], suspectedAbilityIds = [], unresolved = [], sources = [], certainty = 'confirmed' }) => freeze({
  id: `guardian-beast-state:${beastId.replace('guardian-beast:', '')}:${start}`,
  beastId,
  chapterRange: freeze({ start, end }),
  knowledge,
  operationalState,
  hostState,
  visibility,
  knownAbilityIds: freeze(knownAbilityIds),
  suspectedAbilityIds: freeze(suspectedAbilityIds),
  unresolved: freeze(unresolved),
  sourceIds: freeze(sources.map(chapterSourceId)),
  certainty,
});

