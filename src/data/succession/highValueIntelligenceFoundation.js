import { successionArchiveData as predecessorData } from './entitiesInformationConsistency.js';

const ARCHIVE_DATE = '2026-08-02';
const freeze = (values = []) => Object.freeze([...values]);
const unique = (values = []) => [...new Set(values.filter(Boolean))];
const normalize = (value) => String(value || '')
  .normalize('NFKD')
  .replace(/[\u0300-\u036f]/g, '')
  .replace(/[’'`]/g, '')
  .replace(/[^a-zA-Z0-9]+/g, ' ')
  .trim()
  .toLocaleLowerCase();

const canonicalEntities = Object.values(predecessorData)
  .filter(Array.isArray)
  .flat()
  .filter((record) => record?.id && record?.entityType);
const entityById = new Map(canonicalEntities.map((entity) => [entity.id, entity]));
const entitiesByName = new Map();
for (const entity of canonicalEntities) {
  for (const label of [entity.name, ...(entity.aliases || [])]) {
    const key = normalize(label);
    if (!key) continue;
    const current = entitiesByName.get(key) || [];
    current.push(entity);
    entitiesByName.set(key, current);
  }
}

const sourceIdsForChapters = (...chapters) => freeze(unique(chapters.flat().flatMap((chapter) => predecessorData.sources
  .filter((source) => Number(source.chapter) === Number(chapter))
  .map((source) => source.id))));
const entityIdsForNames = (...names) => freeze(unique(names.flat().flatMap((name) => (entitiesByName.get(normalize(name)) || []).map((entity) => entity.id))));
const existingIds = (...ids) => freeze(unique(ids.flat().filter((id) => entityById.has(id))));
const range = (start, end = null) => Object.freeze({ start, end });
const custody = (...entries) => freeze(entries.map((entry) => Object.freeze(entry)));

const baseEntity = ({ id, entityType, slug, name, summary, chapters, chapterRange, canonLevel = 'canon', aliases = [], tags = [], ...extra }) => Object.freeze({
  id,
  entityType,
  slug,
  name,
  summary,
  aliases: freeze(aliases),
  tags: freeze(tags),
  publicationStatus: 'published',
  canonLevel,
  sourceIds: sourceIdsForChapters(chapters),
  chapterRange: chapterRange || range(Math.min(...chapters), null),
  updatedAt: ARCHIVE_DATE,
  ...extra,
});

