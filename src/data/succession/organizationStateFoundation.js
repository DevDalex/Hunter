const chapterSourceId = (number) => `source:chapter-${number}`;
const unique = (values) => [...new Set(values.filter(Boolean))];

const organizationState = ({
  organizationId,
  start,
  end = null,
  status = 'active',
  operationalState,
  authority,
  territoryIds = [],
  objectiveStates = [],
  pressure = [],
  relatedEventIds = [],
  certainty = 'confirmed',
  sources = [start],
}) => Object.freeze({
  id: `organization-state:${organizationId.replace('organization:', '')}:${start}`,
  organizationId,
  chapterRange: Object.freeze({ start, end }),
  status,
  operationalState,
  authority,
  territoryIds: Object.freeze(territoryIds),
  objectiveStates: Object.freeze(objectiveStates),
  pressure: Object.freeze(pressure),
  relatedEventIds: Object.freeze(relatedEventIds),
  certainty,
  sourceIds: Object.freeze(unique(sources.map(chapterSourceId))),
});

