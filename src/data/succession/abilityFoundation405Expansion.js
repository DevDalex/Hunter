const freeze = (value) => Object.freeze(value);
const chapterSourceId = (number) => `source:chapter-${number}`;

const ability = ({ id, slug, name, aliases = [], summary, owners = [], category, activation, conditions = [], limitations = [], costs = [], targets = [], range = 'unknown', duration = 'unknown', knownUses = [], sourceChapters, researchStatus, certainty = 'confirmed' }) => freeze({
  id,
  entityType: 'ability',
  slug,
  name,
  aliases: freeze(aliases),
  summary,
  sourceIds: freeze(sourceChapters.map(chapterSourceId)),
  publicationStatus: 'published',
  canonLevel: 'canon',
  createdAt: '2026-08-11',
  updatedAt: '2026-08-11',
  ownerIds: freeze(owners),
  classification: freeze({ nenTypes: freeze(['unknown']), certainty }),
  category,
  activation,
  conditions: freeze(conditions),
  limitations: freeze(limitations),
  costs: freeze(costs),
  targets: freeze(targets),
  range,
  duration,
  status: 'active',
  knownUses: freeze(knownUses),
  firstChapter: Math.min(...sourceChapters),
  latestChapter: Math.max(...sourceChapters),
  sourceChapterNumbers: freeze([...sourceChapters]),
  researchStatus,
});

