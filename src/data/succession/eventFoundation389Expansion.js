const freeze = (value) => Object.freeze(value);
const characterId = (name) => `character:${String(name).normalize('NFKD').replace(/[\u0300-\u036f]/g, '').toLowerCase().replace(/&/g, ' and ').replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '')}`;
const chapterSourceId = (number) => `source:chapter-${number}`;
const event = ({ slug, name, summary, category, sequence, day, timeOfDay = null, certainty, participants = [], organizations = [], locations = [], abilities = [], causes = [], outcomes = [], stateChanges = [], openQuestions = [], importance = 'major' }) => freeze({
  id: `event:${slug}`,
  entityType: 'event',
  slug,
  name,
  aliases: freeze([]),
  summary,
  sourceIds: freeze([chapterSourceId(389)]),
  publicationStatus: 'published',
  canonLevel: 'canon',
  createdAt: '2026-08-09',
  updatedAt: '2026-08-09',
  category,
  importance,
  chapterRange: freeze({ start: 389, end: 389 }),
  chronology: freeze({ sequence, day, timeOfDay, certainty }),
  participantIds: freeze(participants.map(characterId)),
  organizationIds: freeze(organizations),
  locationIds: freeze(locations),
  abilityIds: freeze(abilities.map((value) => `ability:${value}`)),
  causes: freeze(causes),
  outcomes: freeze(outcomes),
  consequenceEventIds: freeze([]),
  status: 'completed',
  stateChanges: freeze(stateChanges),
  openQuestions: freeze(openQuestions),
});

