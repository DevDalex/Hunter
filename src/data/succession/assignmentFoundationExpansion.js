const ARCHIVE_DATE = '2026-07-24';

const slugify = (value = '') => String(value)
  .normalize('NFKD')
  .replace(/[\u0300-\u036f]/g, '')
  .toLowerCase()
  .replace(/&/g, ' and ')
  .replace(/[^a-z0-9]+/g, '-')
  .replace(/^-+|-+$/g, '');

const characterId = (name) => `character:${slugify(name)}`;
const chapterSourceId = (number) => `source:chapter-${number}`;
const eventId = (slug) => `event:${slug}`;
const shipId = 'location:black-whale';
const tierId = (number) => `${shipId}:tier-${number}`;
const roomId = (number) => `${tierId(1)}:room-${1000 + Number(number)}`;
const justiceId = `${tierId(1)}:justice-bureau`;
const unique = (values) => [...new Set(values.filter(Boolean))];

const assignment = ({
  slug,
  name,
  aliases = [],
  summary,
  person,
  principal = null,
  subject = null,
  locationId = null,
  assignmentType,
  allegiance = null,
  reporting = null,
  status = 'active',
  secrecy = 'public',
  start,
  end = null,
  objective,
  authorityBasis = 'Household or institutional assignment documented in the voyage record.',
  operationalNotes = [],
  relatedEvents = [],
  supersedesAssignmentId = null,
  replacedByAssignmentId = null,
  certainty = 'confirmed',
  canonLevel = 'canon',
  sources,
}) => Object.freeze({
  id: `assignment:${slug}`,
  entityType: 'assignment',
  slug,
  name,
  aliases: Object.freeze(aliases),
  summary,
  sourceIds: Object.freeze(unique((sources || [start]).map(chapterSourceId))),
  publicationStatus: 'published',
  canonLevel,
  createdAt: ARCHIVE_DATE,
  updatedAt: ARCHIVE_DATE,
  personId: characterId(person),
  principalEntityId: principal ? characterId(principal) : null,
  subjectEntityId: subject ? characterId(subject) : null,
  locationId,
  assignmentType,
  allegianceEntityId: allegiance ? characterId(allegiance) : null,
  reportingEntityId: reporting ? characterId(reporting) : null,
  status,
  secrecy,
  chapterRange: Object.freeze({ start, end }),
  objective,
  authorityBasis,
  operationalNotes: Object.freeze(operationalNotes),
  relatedEventIds: Object.freeze(relatedEvents.map(eventId)),
  supersedesAssignmentId,
  replacedByAssignmentId,
  certainty,
});

