const ARCHIVE_DATE = '2026-07-24';

const slugify = (value = '') => String(value)
  .normalize('NFKD')
  .replace(/[\u0300-\u036f]/g, '')
  .toLowerCase()
  .replace(/&/g, ' and ')
  .replace(/[^a-z0-9]+/g, '-')
  .replace(/^-+|-+$/g, '');

const characterId = (name) => `character:${slugify(name)}`;
const organizationId = (slug) => `organization:${slug}`;
const chapterSourceId = (number) => `source:chapter-${number}`;
const abilityId = (slug) => `ability:${slug}`;
const unique = (values) => [...new Set(values.filter(Boolean))];

const shipId = 'location:black-whale';
const tierId = (number) => `${shipId}:tier-${number}`;
const roomId = (number) => `${tierId(1)}:room-${1000 + number}`;

const event = ({
  slug,
  name,
  aliases = [],
  summary,
  category,
  importance = 'major',
  start,
  end = start,
  participants = [],
  organizations = [],
  locations = [],
  abilities = [],
  causes = [],
  outcomes = [],
  consequences = [],
  status = 'completed',
  sources,
  chronology = {},
  stateChanges = [],
  openQuestions = [],
}) => Object.freeze({
  id: `event:${slug}`,
  entityType: 'event',
  slug,
  name,
  aliases: Object.freeze(aliases),
  summary,
  sourceIds: Object.freeze(unique((sources || [start]).map(chapterSourceId))),
  publicationStatus: 'published',
  canonLevel: 'canon',
  createdAt: ARCHIVE_DATE,
  updatedAt: ARCHIVE_DATE,
  category,
  importance,
  chapterRange: Object.freeze({ start, end }),
  chronology: Object.freeze({
    sequence: chronology.sequence || 0,
    day: chronology.day || null,
    timeOfDay: chronology.timeOfDay || null,
    certainty: chronology.certainty || 'approximate',
  }),
  participantIds: Object.freeze(participants.map(characterId)),
  organizationIds: Object.freeze(organizations.map(organizationId)),
  locationIds: Object.freeze(locations),
  abilityIds: Object.freeze(abilities.map(abilityId)),
  causes: Object.freeze(causes),
  outcomes: Object.freeze(outcomes),
  consequenceEventIds: Object.freeze(consequences.map((value) => `event:${value}`)),
  status,
  stateChanges: Object.freeze(stateChanges),
  openQuestions: Object.freeze(openQuestions),
});

